#!/usr/bin/env python3
"""Export the archived Adventure vendor inventories with stable per-vendor stock slots."""
import argparse
from contextlib import closing
import json
from pathlib import Path
import sys
from export_content import ROOT, DEFAULT_DATABASE, connect_readonly, numeric_rows, describe_source
from read_reference_adventure import DEFAULT_SAVE, Reader, records

ANNOT_SAVE = Path.home()/'.local/share/planet-explorers-route-reference/PlanetExplorers/GameSave/save2'
ANNOT_VENDORS = ((20028,153),(20031,158),(20032,163),(20033,143),(20037,148))
LEGACY_STOCK_COUNT = 17

# Stable persistence order. Changing this requires save migration.
VENDORS=((20002,141,(1183,281,1184,285,1185,287,1186,289)),
         (20014,146,(1308,283)),(20011,151,(1337,338,1343,1344,1347,1348,1350)))
def build_outputs(database=DEFAULT_DATABASE,save=DEFAULT_SAVE,annot_save=ANNOT_SAVE):
    archive,sources,_=records(save)
    r=Reader(archive['ArchiveKeyCreature']);r.version(0);entities=r.blob();r.end();entities.version(0)
    actual={}
    for _ in range(entities.count()):
        ident,prefab,body=entities.integer(),entities.string(),entities.blob()
        body.version(2);kind,prototype=body.unpack('ii');actual[ident]=(kind,prototype)
    entities.end()
    with closing(connect_readonly(database)) as db:
        stores,_=numeric_rows(db,'store','store_id');npcs,_=numeric_rows(db,'NPCstore','store_id')
    extra_archive,extra_sources,_=records(annot_save)
    r=Reader(extra_archive['ArchiveKeyCreature']);r.version(0);entities=r.blob();r.end();entities.version(0)
    annot_actual={}
    for _ in range(entities.count()):
        ident,prefab,body=entities.integer(),entities.string(),entities.blob()
        body.version(2);kind,prototype=body.unpack('ii');annot_actual[ident]=(kind,prototype)
    entities.end()
    extended=[]
    for entity,prototype in ANNOT_VENDORS:
        if annot_actual.get(entity)!=(1,prototype):raise ValueError('Archived Annot vendor binding changed')
        actual[entity]=annot_actual[entity]
        matching=[r for r in npcs.values() if int(r['storenpc_id'])==prototype]
        if len(matching)!=1:raise ValueError('Ambiguous Annot NPC store')
        extended.append((entity,prototype,tuple(int(x) for x in matching[0]['adven_single'].split(','))))
    offers=[]
    for entity,prototype,selected in (*VENDORS,*extended):
        if actual.get(entity)!=(1,prototype):raise ValueError('Archived vendor binding changed')
        matching=[r for r in npcs.values() if int(r['storenpc_id'])==prototype]
        if len(matching)!=1:raise ValueError('Ambiguous source NPC store')
        allowed={int(x) for x in matching[0]['adven_single'].split(',')}
        if len(selected)!=len(set(selected)):raise ValueError('Duplicate vendor offer')
        for identity in selected:
            if identity not in allowed:raise ValueError('Offer not in Adventure store')
            row=stores[identity]
            if row['extra_demand']!='0' or row['PreQuestLimit'] not in ('0','1:2,3,4,8'):raise ValueError('Unsupported shop condition')
            offer=dict(entity_id=entity,prototype_id=prototype,store_id=identity,item_id=int(row['item_id']),price=int(row['sale_price2']),limit=int(row['sale_limit']),refresh_seconds=int(row['refresh_time']))
            if not all(0<v<2**31 for v in offer.values()):raise ValueError('Invalid offer value')
            offers.append(offer)
    lines=['/* Generated by tools/export_town_interaction.py; do not edit. */','#ifndef PE_TOWN_OFFERS_H','#define PE_TOWN_OFFERS_H','#include "pe_town_interaction.h"','static const PeTownOffer pe_town_offers[]={']
    for o in offers:lines.append('    {'+','.join(str(x) for x in o.values())+'},')
    lines+=['};','_Static_assert(sizeof pe_town_offers/sizeof pe_town_offers[0]==PE_TOWN_STOCK_CAPACITY,"Town stock persistence count");','#endif','']
    manifest=dict(schema=2,legacy_stock_count=LEGACY_STOCK_COUNT,scope='Three bounded starting catalogs and all five archived Annot buy catalogs. Metadata/crafting closure does not implement all equipment, consumables or deployables; no sell/buyback.',sources=[describe_source(database)]+[describe_source(p) for p in sources+extra_sources],offers=offers,
        conditions='UIShopWnd.UpdataShop leaves bPass true for type1 limits even without completed missions. Type2 rows are not included.',refresh='On open, strict elapsed>refresh_seconds resets stock; each nonempty entry resets creation time even when not refreshed.')
    return {'pe_town_offers.h':'\n'.join(lines).encode(),'pe_town_offers.json':(json.dumps(manifest,indent=2)+'\n').encode()}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path,default=ROOT/'rebuild/generated');a=p.parse_args()
    try:
        for name,data in build_outputs().items():
            path=a.output/name
            if a.check:
                if not path.exists() or path.read_bytes()!=data:raise ValueError('Stale '+name)
            else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        print('Town offers checked' if a.check else 'Town offers generated')
    except (OSError,ValueError,KeyError) as e:print(e,file=sys.stderr);return 1
    return 0
if __name__=='__main__':raise SystemExit(main())
