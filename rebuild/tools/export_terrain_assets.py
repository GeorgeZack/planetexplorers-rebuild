#!/usr/bin/env python3
"""Recover installed terrain atlases and validate their original source bindings.

Requires UnityPy and Pillow. Inputs are read-only. --check regenerates in memory
and compares every declared output; no original game process is started.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_INSTALL = Path.home()/'.local/share/Steam/steamapps/common/Planet Explorers'
DEFAULT_OUTPUT = ROOT/'rebuild/build/reference-assets/terrain'
HEADER = ROOT/'rebuild/generated/pe_terrain_materials.h'
MATERIAL = ROOT/'Assets/Terrain/Materials/TerrainSet1Mat.mat'
SHADER = ROOT/'Assets/Terrain/Voxelform2/Voxelform/Source/Shaders/VoxelBlend/VoxelBlend_Def.shader'
INCLUDE = SHADER.with_name('VoxelBlend.cginc')
DATABASE = ROOT/'Assets/Resources/DataBase/localData.bytes'
PAINT = ROOT/'Assets/Resources/RandomMapXML/tmpPaintVxMat.xml'
PARAMETERS = {'_TileSize': .25, '_TileSize_1': .5, '_Repetition': 3.,
              '_Repetition_1': 10., '_Indent': 8.}
ALIASES = {'dirt': 1, 'stone': 17, 'grass': 3}


def sha256(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024*1024), b''):
            h.update(chunk)
    return h.hexdigest()


def properties(entries):
    return {(k['name'] if isinstance(k, dict) else k): v for k, v in entries}


def meta_guid(path):
    match = re.search(r'^guid: ([0-9a-f]{32})$', Path(str(path)+'.meta').read_text(), re.M)
    if not match:
        raise ValueError('Missing source GUID: '+str(path))
    return match[1]


def reference_guid(obj, pointer):
    raw = bytes(obj.assets_file.externals[pointer['m_FileID']-1].guid).hex()
    return ''.join(raw[i:i+2][::-1] for i in range(0, 32, 2))


def material_slot(material_id):
    """Source CalcBaseUV, including the one-based vertex material encoding."""
    if type(material_id) is not int or not 1 <= material_id <= 84:
        raise ValueError('Terrain material ID outside supported source atlas')
    index = material_id - 1
    if index >= 68:
        atlas, tile, side = 5, index-68, 4
    elif index >= 64:
        atlas, tile, side = 4, index-64, 2
    else:
        atlas, tile, side = index//16, index%16, 4
    return dict(source_id=material_id, atlas=atlas, column=tile%side,
                row_from_bottom=tile//side, grid=side,
                repetition=10. if side == 2 else 3.,
                inset_fraction=8./512. if side == 2 else 8./256.)


def header_bytes():
    return ('''/* Generated by tools/export_terrain_assets.py; do not edit. */
#ifndef PE_TERRAIN_MATERIALS_H
#define PE_TERRAIN_MATERIALS_H
#define PE_TERRAIN_ATLAS_COUNT 6
#define PE_TERRAIN_MATERIAL_COUNT 84
static const int pe_terrain_diffuse_size[6] = {2048, 2048, 1024, 2048, 2048, 2048};
#define PE_TERRAIN_INDENT 8.0f
#define PE_TERRAIN_REPETITION 3.0f
#define PE_TERRAIN_REPETITION_LARGE 10.0f
/* Representative source materials for the synthetic sandbox palette only. */
#define PE_TERRAIN_SOURCE_DIRT 1
#define PE_TERRAIN_SOURCE_STONE 17
#define PE_TERRAIN_SOURCE_GRASS 3
#endif
''').encode()


def prepare(install):
    import UnityPy
    from PIL import Image
    source_env = UnityPy.load(str(MATERIAL))
    source, = [o for o in source_env.objects if o.type.name == 'Material']
    source_tree = source.read_typetree()
    if reference_guid(source, source_tree['m_Shader']) != meta_guid(SHADER):
        raise ValueError('Source material shader changed')
    source_props = source_tree['m_SavedProperties']
    source_tex = properties(source_props['m_TexEnvs'])
    for name, value in PARAMETERS.items():
        if properties(source_props['m_Floats']).get(name) != value:
            raise ValueError('Unsupported source parameter '+name)
    # These expressions define the recovered mapping and coordinate contract.
    shader_text = INCLUDE.read_text()
    for expression in ('o.weights.xyz = matIdx-1;', 'if(index >= 68)',
                       'if(index >= 64)', 'normalweights = (normalweights - 0.2) * 7;',
                       'i.worldPos.zy', 'i.worldPos.zx', '0.73*log(0.04*dot(dist,dist))'):
        if expression not in shader_text:
            raise ValueError('Source shader contract changed: '+expression)
    resource_path = install/'PE_Client_Data/resources.assets'
    env = UnityPy.load(str(resource_path))
    # Only inspect this file, not every automatically loaded dependency.
    resource_file = next(f for f in env.files.values() if getattr(f, 'name', '').endswith('resources.assets'))
    objects = resource_file.objects
    materials = [o for o in objects.values() if o.type.name == 'Material'
                 and o.read_typetree().get('m_Name') == 'TerrainSet1Mat']
    if len(materials) != 1:
        raise ValueError('Expected one installed TerrainSet1Mat')
    installed = materials[0]
    installed_tree = installed.read_typetree()
    installed_props = installed_tree['m_SavedProperties']
    if properties(installed_props['m_Floats']) != properties(source_props['m_Floats']):
        raise ValueError('Installed/source terrain float properties differ')
    tex = properties(installed_props['m_TexEnvs'])
    # PPtr resolves external shader through the loaded resource dependency table.
    shader = installed.read().m_Shader.deref().read_typetree()
    if shader['m_Name'] != 'VoxelBlend_Def' or not shader.get('m_Script', '').startswith('Shader "VoxelMultiMaterial_Def"'):
        raise ValueError('Installed terrain shader differs: '+shader['m_Name'])
    source_inputs = {MATERIAL, Path(str(MATERIAL)+'.meta'), SHADER, INCLUDE, DATABASE, PAINT}
    outputs, textures = {}, []
    for kind, prop in [('diffuse', '_DiffuseTex_'), ('normal', '_NormalMap_')]:
        for slot in range(6):
            name = prop+str(slot)
            source_path = ROOT/f'Assets/Terrain/textures/terrainset{slot+1}_{"d" if kind == "diffuse" else "n"}.jpg'
            if reference_guid(source, source_tex[name]['m_Texture']) != meta_guid(source_path):
                raise ValueError('Source texture binding changed: '+name)
            source_inputs.update((source_path, Path(str(source_path)+'.meta')))
            textures.append((kind+str(slot)+'.png', name, source_path))
    normspec_source = ROOT/'Assets/Resources/terrainNormSpec.png'
    if reference_guid(source, source_tex['_NormSpecPowerTex']['m_Texture']) != meta_guid(normspec_source):
        raise ValueError('Source normal/spec lookup changed')
    source_inputs.update((normspec_source, Path(str(normspec_source)+'.meta')))
    textures.append(('normspec.png', '_NormSpecPowerTex', normspec_source))
    records = []
    for filename, property_name, source_path in textures:
        binding = tex[property_name]
        if (binding['m_Texture']['m_FileID'] != 0
                or binding['m_Scale'] != {'x': 1., 'y': 1.}
                or binding['m_Offset'] != {'x': 0., 'y': 0.}):
            raise ValueError('Unexpected installed texture transform/reference')
        texture_obj = objects[binding['m_Texture']['m_PathID']]
        texture = texture_obj.read()
        if texture.m_Name != source_path.stem:
            raise ValueError('Installed/source texture names differ')
        image = texture.image
        expected = (256, 2) if filename == 'normspec.png' else ((1024,1024) if filename == 'diffuse2.png' or filename.startswith('normal') else (2048,2048))
        if image.size != expected:
            raise ValueError('Unexpected installed texture dimensions: '+filename)
        # UnityPy produces conventional top-down images; raylib consumes row0 at
        # UV v=0. Flip once here to retain original Unity bottom-origin atlas UVs.
        image = image.convert('RGBA').transpose(Image.Transpose.FLIP_TOP_BOTTOM)
        buffer = io.BytesIO()
        image.save(buffer, format='PNG', compress_level=6)
        outputs[filename] = buffer.getvalue()
        records.append(dict(file=filename, property=property_name,
            source=str(source_path.relative_to(ROOT)), source_guid=meta_guid(source_path),
            installed_path_id=texture_obj.path_id, installed_name=texture.m_Name,
            installed_format=int(texture.m_TextureFormat), width=image.width, height=image.height,
            sha256=hashlib.sha256(outputs[filename]).hexdigest()))
    with sqlite3.connect(f'file:{DATABASE}?mode=ro', uri=True) as db:
        db.row_factory = sqlite3.Row
        resources = {int(r['ID']): dict(r) for r in db.execute('select * from resource')}
    slots = [dict(material_slot(i), resource=resources.get(i)) for i in range(1,85)]
    manifest = dict(format='PE-terrain-assets-1',
        installed_resource='PE_Client_Data/resources.assets', installed_sha256=sha256(resource_path),
        installed_material_path_id=installed.path_id, shader='VoxelMultiMaterial_Def', installed_shader_asset_name=shader['m_Name'],
        material_parameters=properties(source_props['m_Floats']),
        texture_orientation='PNG flipped vertically from UnityPy image; sample Unity bottom-origin UV directly in raylib',
        normal_encoding='Installed DXT5nm channels preserved; current source OpenGL surf ignores normal perturbation',
        source_inputs={str(p.relative_to(ROOT)): sha256(p) for p in sorted(source_inputs)},
        textures=records, materials=slots,
        synthetic_palette_aliases=ALIASES,
        synthetic_palette_status='Representative source selection; not the original Adventure terrain generator',
        scope='84 source atlas slots; source resource rows preserve unknown ? names; no world generation, lighting, or streaming parity')
    outputs['manifest.json'] = (json.dumps(manifest, indent=2, ensure_ascii=False, sort_keys=True)+'\n').encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--install', type=Path, default=DEFAULT_INSTALL)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--header', type=Path, default=HEADER)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = prepare(args.install)
    paths = {args.output/name: data for name, data in outputs.items()}
    paths[args.header] = header_bytes()
    if args.check:
        mismatches = [str(path) for path, data in paths.items() if not path.exists() or path.read_bytes() != data]
        if mismatches:
            raise SystemExit('Terrain output differs: '+', '.join(mismatches))
        print(f'Terrain assets match ({len(paths)} files)')
    else:
        for path, data in paths.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f'Exported terrain assets ({len(paths)} files) to {args.output}')


if __name__ == '__main__':
    main()
