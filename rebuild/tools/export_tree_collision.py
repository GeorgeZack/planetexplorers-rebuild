#!/usr/bin/env python3
"""Generate headless tree11 collision constants from the verified source prefab.

Uses the same decoder and mesh-identity checks as the sandbox visual exporter.
No installed game, recovered graphics, or runtime Unity dependency is required.
"""
import argparse
from pathlib import Path
from export_sandbox_world_assets import ROOT, source_capsule

OUTPUT = ROOT/'rebuild/generated/pe_tree_collider.h'


def generate():
    binary, source = source_capsule()
    values = source['center'] + [source['radius'], source['height']]
    text = ('/* Generated by tools/export_tree_collision.py; do not edit.\n'
            f" * {source['prefab']}\n * SHA256 {source['prefab_sha256']}\n"
            f" * Mesh GUID {source['mesh_guid']}; CapsuleCollider {source['component']}. */\n"
            '#ifndef PE_TREE_COLLIDER_GENERATED_H\n#define PE_TREE_COLLIDER_GENERATED_H\n'
            '/* Local center XYZ, radius, total height; Y axis, enabled/nontrigger. */\n'
            'static const float pe_tree_collider_source[5] = {\n    '+
            ', '.join(float(v).hex()+'f' for v in values)+'\n};\n#endif\n')
    return text, binary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, binary = generate()
    sidecar = ROOT/'rebuild/build/reference-assets/sandbox-world/tree-collider.pesc'
    if sidecar.is_file() and sidecar.read_bytes() != binary:
        raise ValueError('Recovered visual PESC differs from original source collider')
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise ValueError('Generated tree collider differs; regenerate')
    else:
        OUTPUT.write_text(text)
    print(('Verified' if args.check else 'Generated')+' source tree collider and available PESC')


if __name__ == '__main__':
    main()
