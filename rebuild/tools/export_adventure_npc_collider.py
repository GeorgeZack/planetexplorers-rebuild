#!/usr/bin/env python3
"""Recover supplier FemaleModel's physical and idle picking capsules from source."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
PREFAB = ROOT/'Assets/Resources/Prefab/PlayerPrefab/FemaleModel.prefab'
OUTPUT = ROOT/'rebuild/generated/pe_adventure_npc_collider.h'


def source_capsule(sex="female"):
    if sex not in ("female","male"): raise ValueError("Unknown capsule sex")
    prefab = ROOT/("Assets/Resources/Prefab/PlayerPrefab/"+sex.title()+"Model.prefab")
    import UnityPy
    objects = {o.path_id: o for o in UnityPy.load(str(prefab)).objects}
    transforms = {o.path_id: o.read_typetree() for o in objects.values() if o.type.name == 'Transform'}
    by_go = {t['m_GameObject']['m_PathID']: i for i, t in transforms.items()}

    def capsule(path_id, name, layer, trigger):
        c = objects[path_id].read_typetree()
        go = objects[c['m_GameObject']['m_PathID']].read_typetree()
        if (not c['m_Enabled'] or c['m_IsTrigger'] != trigger or c['m_Direction'] != 1
                or go['m_Name'] != name or go['m_Layer'] != layer or not go['m_IsActive']):
            raise ValueError('Unexpected source supplier capsule identity or flags')
        current = by_go[c['m_GameObject']['m_PathID']]
        while current:
            t = transforms[current]
            if (t['m_LocalPosition'] != dict(x=0., y=0., z=0.)
                    or t['m_LocalScale'] != dict(x=1., y=1., z=1.)
                    or t['m_LocalRotation'] != dict(x=0., y=0., z=0., w=1.)):
                raise ValueError('Supplier capsule requires nonidentity transform handling')
            current = t['m_Father']['m_PathID']
        values = [c['m_Center'][axis] for axis in 'xyz']+[c['m_Radius'], c['m_Height']]
        if values[0] != 0 or values[2] != 0 or not 0 < values[3] <= 2 or not 2*values[3] <= values[4] <= 4:
            raise ValueError('Invalid supplier upright capsule')
        return dict(component=path_id, name=name, layer=layer, center=values[:3],
                    radius=values[3], height=values[4], direction=1, enabled=True, trigger=trigger)

    body = capsule(13600000 if sex=='female' else 13654112, 'Model', 10, False)
    defence = capsule(13690738 if sex=='female' else 13653336, 'Defence', 25, True)
    binary = b'PESC'+struct.pack('<I5fII', 1, *body['center'], body['radius'], body['height'], 1, 1)
    metadata = dict(prefab=str(prefab.relative_to(ROOT)),
                    prefab_sha256=hashlib.sha256(prefab.read_bytes()).hexdigest(),
                    physical=body, defence=defence,
                    outer_growth=dict(radius=.1, height=.2,
                        source='Assets/Scripts/PeEntity/Cmpt/BiologyViewCmpt.cs:BuildOutCollider'))
    return binary, metadata


def generate():
    binary, source = source_capsule()
    text = ('/* Generated by tools/export_adventure_npc_collider.py; do not edit.\n'
            f" * {source['prefab']}\n * SHA256 {source['prefab_sha256']} */\n"
            '#ifndef PE_ADVENTURE_NPC_COLLIDER_GENERATED_H\n#define PE_ADVENTURE_NPC_COLLIDER_GENERATED_H\n')
    for role in ('physical', 'defence'):
        c = source[role]
        values = c['center']+[c['radius'], c['height']]
        text += (f"/* CapsuleCollider {c['component']}, layer{c['layer']}; center XYZ/radius/height. */\n"
                 f'static const float pe_adventure_npc_{role}[5] = {{\n    '+
                 ', '.join(float(v).hex()+'f' for v in values)+'\n};\n')
    return text+'#endif\n', binary, source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, help='Optional new/existing directory for physical PESC and source manifest')
    args = parser.parse_args()
    text, binary, source = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise ValueError('Generated supplier collider differs; regenerate')
        if args.output and ((args.output/'supplier-collider.pesc').read_bytes() != binary
                            or json.loads((args.output/'supplier-collider.json').read_text()) != source):
            raise ValueError('Exported supplier collider differs from source')
    else:
        OUTPUT.write_text(text)
        if args.output:
            args.output.mkdir(parents=True, exist_ok=True)
            (args.output/'supplier-collider.pesc').write_bytes(binary)
            (args.output/'supplier-collider.json').write_text(json.dumps(source, indent=2)+'\n')
    print(('Verified' if args.check else 'Generated')+' original supplier capsules')


if __name__ == '__main__':
    main()
