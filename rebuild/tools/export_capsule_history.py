#!/usr/bin/env python3
"""Guard capsule history source methods and qualified installed Unity numerics."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys
from export_content import ROOT, describe_source
from export_starter_outfit import body, uncomment

SOURCE_FILES = ('Assets/Scripts/Attack/PECapsuleTrigger.cs',
                'Assets/Scripts/ZhouXun/Voxel Creation/Scripts/WhiteCat/Common/Utility.cs')
DEFAULT_UNITY = Path.home() / '.local/share/Steam/steamapps/common/Planet Explorers/PE_Client_Data/Managed/UnityEngine.dll'
UNITY_SHA256 = 'f728161940fbb8f27659c979bfcabe3f544002858779abfaa1143065926c051b'
CONTRACTS = (
    (0, 'trigger_update', r'public\s+void\s+Update\s*\(', '37d5e50b1ebd2a6dd4622f941424d5be34cc02f06fa433c0c23ec5678c73cd26'),
    (0, 'capsule_overlap', r'bool\s+CheckCollision\s*\(Vector3 pos1, Vector3 pos2, PECapsuleTrigger', '035e2c8bff200babe1374875bc420ac5997d894242d105585f995f53a20b1f7d'),
    (0, 'history_sampling', r'public\s+bool\s+CheckCollision\s*\(PECapsuleTrigger', '8a89b30554c8fa0b00d1cc9a73a411c818ea4b562cd529a0b1f64bd6ba9e9258'),
    (1, 'point_segment', r'public\s+static\s+Vector3\s+ClosestPoint\s*\(', 'b359a8657f0d558eacddbf2e26943c82b0df18fd1e4f26dc842a05a5d47e3ffb'),
    (1, 'segment_segment', r'public\s+static\s+void\s+ClosestPoint\s*\(', '18a8e4b0d22fa5bda63374e5ade81666b4ec4fcf95844dcabe9b7d50e183c201'),
)


def validate_sources(root):
    texts = [uncomment((root / p).read_text(encoding='utf-8-sig')) for p in SOURCE_FILES]
    for index, label, pattern, expected in CONTRACTS:
        if hashlib.sha256(body(texts[index], pattern).encode()).hexdigest() != expected:
            raise ValueError(label + ' source contract changed')
    return [describe_source(root / p) for p in SOURCE_FILES]


def build_outputs(source_root=ROOT, unity_engine=DEFAULT_UNITY):
    sources = validate_sources(source_root)
    data = unity_engine.read_bytes()
    if hashlib.sha256(data).hexdigest() != UNITY_SHA256:
        raise ValueError('Unqualified UnityEngine assembly; inspect managed IL again')
    # These ldc.r4 operands were read with mono_method_get_header from the
    # pinned assembly. Require their complete method IL too, not a text guess.
    il = {
        'Vector3.op_Equality': '020328e004000628d104000622fee6db2efe042a',
        'Vector3.Normalize(Vector3)': '0228cf0400060a0622acc527374308000000020628e40400062a28d50400062a',
    }
    for name, value in il.items():
        if bytes.fromhex(value) not in data:
            raise ValueError('Qualified method IL missing: ' + name)
    rule = dict(vector_equality_squared=struct.unpack('<f', bytes.fromhex('fee6db2e'))[0],
                normalize_magnitude=struct.unpack('<f', bytes.fromhex('acc52737'))[0],
                point_segment_squared_cutoff=struct.unpack('<f', struct.pack('<f', 1e-6))[0],
                sampling_distance_factor=.5, strict_overlap=True,
                count_one_uses_previous=True, target_uses_current=True,
                contact_distance=0, parent_center='entity.centerPos')
    manifest = dict(schema=1, source_files=sources,
        method_guards={label: digest for _, label, _, digest in CONTRACTS},
        unity_engine=dict(name='UnityEngine.dll', sha256=UNITY_SHA256, method_il=il),
        rule=rule, native_limits=dict(max_samples=4096, max_absolute_coordinate=1000000,
                                    max_radius=1000000, fail_closed=True),
        arithmetic='Installed Mono scalar expression intermediates are wider than float; '
                   'Vector3 components and assigned float locals round. Preserve WhiteCat '
                   'NaN parallel fallback and strict tie order. This is not the generic double closest solver.',
        qualification='Standalone original-source managed math against installed Mono/UnityEngine; '
                      'no game, engine objects, graphics, input or saves. Native finite/work bounds are adapters.')
    header = '''/* Generated by export_capsule_history.py; do not edit. */
#ifndef PE_CAPSULE_HISTORY_SOURCE_H
#define PE_CAPSULE_HISTORY_SOURCE_H
#define PE_CAPSULE_EQUALITY_SQUARED 9.99999944e-11f
#define PE_CAPSULE_NORMALIZE_MAGNITUDE 9.99999975e-6f
#define PE_CAPSULE_POINT_SEGMENT_SQUARED 1e-6f
#define PE_CAPSULE_SAMPLE_DISTANCE_FACTOR .5f
#endif
'''
    return {'pe_capsule_history_source.h': header.encode(),
            'pe_capsule_history_source.json': (json.dumps(manifest, indent=2) + '\n').encode()}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--unity-engine', type=Path, default=DEFAULT_UNITY)
    p.add_argument('--output', type=Path, default=ROOT / 'rebuild/generated')
    p.add_argument('--check', action='store_true')
    a = p.parse_args(argv)
    try:
        for name, data in build_outputs(unity_engine=a.unity_engine).items():
            path = a.output / name
            if a.check:
                if not path.is_file() or path.read_bytes() != data:
                    raise ValueError('Stale generated ' + name)
            else:
                a.output.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
        print('Capsule history metadata ' + ('checked' if a.check else 'generated'))
        return 0
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
