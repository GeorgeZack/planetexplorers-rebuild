HIT_DIGEST = '6acb706983e80b321e29e8033574407bab1c6eece2cdb803ba89016e5bfdd74f'
PROFILE_DIGEST = 'f3de49e4520b3fa1d6ca86461d354cad55083ceb509d8ee5a6093f5f3eeeb8de'
def digest(value): return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode()).hexdigest()
def validate_sources(root):
 for path,pattern,expected in METHODS:
  require(hashlib.sha256(body(uncomment(read_text(root/path)),pattern).encode()).hexdigest()==expected,'Hit IK source changed: '+path)
 require('guid: '+CONTROL_GUID in read_text(root/(CONTROL+'.meta')),'IK controller GUID changed')
 return [describe_source(root/p) for p in SOURCES]
def qualify(model,param_guid):
 require([k for k,v in model.items() if v.get('script_guid')==CONTROL_GUID]==[COMPONENT],'IK controller identity changed')
 owner=model[COMPONENT]['data']
 require(owner['m_Enabled']==1 and owner['m_Weight']==1,'IK controller master state changed')
 raw=owner['m_HitReaction'];require(digest(raw)==HIT_DIGEST,'Hit IK bindings/curves changed')
 params=[v['data'] for v in model.values() if v.get('script_guid')==param_guid]
 require(len(params)==1,'Expected one BeatParam')
 profile={k:params[0][k] for k in ('m_RandomScale','m_ForceToHitWeight','m_ForceToHitTime')}
 require(digest(profile)==PROFILE_DIGEST,'Hit IK force profile changed')
 parts=[]
 for part in raw['m_HitParts']:
  transforms=[]
  for ref in part['m_PartTrans']:
   require(ref['m_FileID']==0 and model[ref['m_PathID']]['kind']=='Transform','Invalid hit transform')
   transform=model[ref['m_PathID']]['data']; go=model[transform['m_GameObject']['m_PathID']]['data']
   transforms.append(dict(id=ref['m_PathID'],name=go['m_Name']))
  links=[]
  for link in part['m_Effect']['m_Effects']:
   curves=[]
   for field in ('m_ForceDir','m_UpDir'):
    c=link[field]
    # The sole looping pre-infinity is strictly below zero and unreachable
    # for elapsed/duration >= 0. Preserve it as evidence, never claim wrap support.
    require(c['m_PreInfinity']==2 or (c['m_PreInfinity']==1 and c['m_Curve'][0]['time']<0),'Reachable unsupported pre-infinity')
    clone=dict(c,m_PreInfinity=2);curves.append(curve(clone,part['m_Name']+field))
   links.append(dict(effector=link['m_Effector'],pin=bool(link['m_PinWordPos']),force=curves[0],up=curves[1]))
  parts.append(dict(name=part['m_Name'],transforms=transforms,links=links))
 return dict(component=COMPONENT,weight_scale=raw['weightScale'],parts=parts,profile=profile)
def build_outputs(root=ROOT):
 sources=validate_sources(root);data=qualify(read_objects(root/MODEL),guid(root,PARAM))
 lines=['/* Generated by export_hit_ik.py; do not edit. */\n#ifndef PE_HIT_IK_SOURCE_H\n#define PE_HIT_IK_SOURCE_H\n',
 'typedef struct {float time,value,in_slope,out_slope;} PeHitIkKey;\n',
 'typedef struct {const PeHitIkKey *keys;unsigned count;} PeHitIkCurve;\n',
 'typedef struct {unsigned effector;int pin;PeHitIkCurve force,up;} PeHitIkLink;\n',
 'typedef struct {const unsigned *transforms;unsigned transform_count;const PeHitIkLink *links;unsigned link_count;} PeHitIkPart;\n']
 count=0
 def keys(rows):
  nonlocal count
  name='pe_hit_ik_keys_%d'%count;count+=1
  lines.append('static const PeHitIkKey %s[]={%s};\n'%(name,','.join('{%s,%s,%s,%s}'%tuple(f(k[v]) for v in ('time','value','in_slope','out_slope')) for k in rows)))
  return '{%s,%d}'%(name,len(rows))
 part_rows=[]
 for i,p in enumerate(data['parts']):
  links=['{%d,%d,%s,%s}'%(l['effector'],l['pin'],keys(l['force']),keys(l['up'])) for l in p['links']]
  lines.append('static const unsigned pe_hit_ik_transforms_%d[]={%s};\n'%(i,','.join(str(t['id']) for t in p['transforms'])))
  lines.append('static const PeHitIkLink pe_hit_ik_links_%d[]={%s};\n'%(i,','.join(links)))
  part_rows.append('{pe_hit_ik_transforms_%d,%d,pe_hit_ik_links_%d,%d}'%(i,len(p['transforms']),i,len(links)))
 lines.append('static const PeHitIkPart pe_hit_ik_parts[]={%s};\n'%','.join(part_rows))
 for name,field in [('weight','m_ForceToHitWeight'),('time','m_ForceToHitTime')]:
  lines.append('static const PeHitIkCurve pe_hit_ik_%s_curve=%s;\n'%(name,keys(curve(data['profile'][field],field))))
 lines.append('static const float pe_hit_ik_random_scale=%s;\n'%f(data['profile']['m_RandomScale']))
 lines.append('#endif\n')
 metadata=dict(schema=1,source_files=sources,binding=data,method_guards=[dict(path=p,pattern=r,sha256=s) for p,r,s in METHODS],
 scope='Disconnected female hit-IK requests. No FinalIK solve, pose, host, stun or knockback.',
 semantics='Null and Repulsed branches request hit IK after angle force scaling, using an independent injected random draw. Exact transform membership starts every matching part. Repeated hits replace that part clock/direction/root origin. weightScale applies twice. Pinned links subtract world root displacement. Duplicate links and overlapping part bindings are intentional source data.',
 arithmetic='Finite-key polynomial order follows qualified Unity5 curves; not bit-exact Mono. One pre-infinity loop is unreachable for nonnegative progress.')
 return {'pe_hit_ik_source.h':''.join(lines).encode(),'pe_hit_ik_source.json':(json.dumps(metadata,indent=2)+'\n').encode()}
def main(argv=None):
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path,default=ROOT/'rebuild/generated');a=p.parse_args(argv)
 try:
  for name,data in build_outputs().items():
   if a.check: require((a.output/name).is_file() and (a.output/name).read_bytes()==data,'Stale or missing '+name)
   else: a.output.mkdir(parents=True,exist_ok=True);(a.output/name).write_bytes(data)
 except (OSError,ValueError,KeyError,ImportError,IndexError) as error: print(error,file=sys.stderr);return 1
 return 0
if __name__=='__main__': raise SystemExit(main())
