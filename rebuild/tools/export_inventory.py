#!/usr/bin/env python3
"""Guard source package capacity/classification, stack operations and sort metadata."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from export_content import ROOT, DEFAULT_DATABASE, connect_readonly, numeric_rows, describe_source

