GUARDS.update({'Assets/Scripts/Items/ItemManager.cs': '39de5d06becf84fd99b5af56f6121dee0ee1642b1e4e358af2e4e629ad409ade', 'Assets/Scripts/Items/ItemPak/ShortCut.cs': '49a694d86c5127707a9dd928a01b766808bcdfc161e548bb130c064d616af2e7'})

def build_outputs(root=ROOT, database=None):
    paths=[]
    for relative, expected in GUARDS.items():
        path=root/relative
        if hashlib.sha256(path.read_bytes()).hexdigest()!=expected:
            raise ValueError('Inventory source changed: '+relative)
        paths.append(path)
    database=database or root/DEFAULT_DATABASE.relative_to(ROOT)
    db=connect_readonly(database)
    try:
        rows,_=numeric_rows(db,'PrototypeItem','id')
        items=[]
        for identity,row in sorted(rows.items()):
            tab,label=int(row['tab']),int(row['sort'])
            if tab<0 or tab>3:raise ValueError('Invalid source item category')
            items.append(dict(id=identity,category=tab,sort_label=label,quest_item=row['category']=='Quest Item'))
    finally:db.close()
    header='/* Generated by export_inventory.py; regenerate, do not edit. */\n#ifndef PE_INVENTORY_SOURCE_H\n#define PE_INVENTORY_SOURCE_H\n#define PE_INVENTORY_SOURCE_CAPACITY 420\ntypedef struct { int id, category, sort_label, quest_item; } PeInventorySourceItem;\nstatic const PeInventorySourceItem pe_inventory_source_items[] = {\n'
    header+=''.join('    {%d,%d,%d,%d},\n'%(r['id'],r['category'],r['sort_label'],r['quest_item']) for r in items)
    header+='};\n#endif\n'
    manifest=dict(format_version=1,sources=[describe_source(p) for p in paths]+[describe_source(database)],
        contract=dict(category_capacity=420,categories=['Item','Equipment','Resource','Armor'],
          classification='ItemProto.tabIndex loaded from PrototypeItem.tab',
          split='strict subset into first empty category slot, source subtracts before add',
          drag='same-category occupied slot exchanges even matching prototypes',
          sort=['Reduce merges stackable prototypes','sortLabel ascending','prototype ID ascending','count ascending'],
          discard=dict(confirmation=8000055,whole_selected_stack=True,protected_category='Quest Item',protected_id_quotient=9,partial='Split first')),
        items=items,
        native_adapters=['Split and all transfers fail atomically.',
          'Stack quickslots remain prototype keyed; durable identities and wear retain one owner.',
          'Stable equal-key sorting; explicit merge convenience uses source stack limits.',
          'Separate mission package, new-item flags and multiplayer replication are not implemented.'])
    return {'pe_inventory_source.h':header.encode(),'pe_inventory_source.json':(json.dumps(manifest,indent=2)+'\n').encode()}

def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=Path,default=ROOT/'rebuild/generated')
    args=parser.parse_args(argv)
    try:
        for name,data in build_outputs().items():
            path=args.output/name
            if args.check:
                if not path.is_file() or path.read_bytes()!=data:raise ValueError('Stale inventory output '+name)
            else:
                path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    except (OSError,ValueError) as error:
        print(error,file=sys.stderr);return 1
    print('Inventory source checked' if args.check else 'Inventory source generated');return 0
if __name__=='__main__':raise SystemExit(main())
