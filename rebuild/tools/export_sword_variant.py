#!/usr/bin/env python3
"""Export the actual EntityPlayer Sword branch thresholds and motor cap offline."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from export_content import ROOT
from export_starter_outfit import body, uncomment
import export_attack_playback as player

SOURCE_FILES=player.SOURCE_FILES
ACTION=player.ACTION
GUARDS={'bool\\s+UpdateSkillState\\s*\\(': '97f3cd0ce820e913238f98a22fddff1adb11d042295c3132ab9c33d00a864c4b',
 'void\\s+ApplySkill\\s*\\(': 'f785245f446a7c134821c4f6a056eeedde9d1dcee87670b55e63ef1fbb15ea9f'}


def validate_sources(root=ROOT):
    provenance=player.validate_sources(root)
    text=uncomment((root/ACTION).read_text(encoding='utf-8-sig'))
    for pattern,expected in GUARDS.items():
        if hashlib.sha256(body(text,pattern).encode()).hexdigest()!=expected:
            raise ValueError('Sword variant/motor source contract changed: '+pattern)
    return provenance


def build_outputs(root=ROOT):
    provenance=validate_sources(root)
    definition,_=player.source_definition(root)
    action=definition['action']
    rule=dict(move_speed=action['m_MoveAttackSpeed'],sprint_speed=action['m_SprintAttackSpeed'],velocity_change_limit=12.)
    if rule['move_speed']!=4.5 or rule['sprint_speed']!=7:
        raise ValueError('Instantiated player thresholds changed')
    metadata=dict(schema=1,source_files=provenance,source_method_guards=GUARDS,
        binding={k:definition[k] for k in ('component_path_id','game_object_path_id','script_guid','action_field')},
        rule=rule,semantics=dict(precedence=['air mask','motor present and spine in water','sprint','running','ordinary'],
            moving='Movement component exists AND velocity.magnitude > move_speed',
            sprint='Movement component exists AND velocity.magnitude > sprint_speed',
            magnitude='Full XYZ vector, no projection onto ground/body plane; finite native input policy. Unity Mathf.Sqrt receives a single-precision squared magnitude and returns a float.',
            numeric_adapter='C uses wider sum-of-products then rounds to float at Mathf.Sqrt argument; double sqrt then float result, matching the already-inspected installed Mono scalar expression behavior. Not every Unity runtime/compiler is qualified.',
            ordinary='All remaining ground/nonwater velocities, including walking and exactly4.5; not a request-for-no-input condition.',
            absent_movement='Ordinary ground branch; air and water still take precedence.',
            capability='Branch identification alone does not enable air/water/sprint presentation or first-person; no action/stamina admission or motion integration.',
            motor='Horizontal request minus current horizontal velocity: if magnitude >=12, normalized difference *12 + current. Cap per update, not acceleration*dt.'),
        numerical_evidence=dict(tool='rebuild/tools/qualify_sword_variant.py', report='docs/reference/sword-variant-numerics.json', compared_vectors=4101, qualification='Separate offline installed-Mono replay; exporter does not run arithmetic proof.'),
        installed='Normal generation checks source prefab. Optional --game verifies the actual installed serialized Motion_Equip payload without running the game; report remains local.')
    header='''/* Generated by export_sword_variant.py; do not edit. */
#ifndef PE_SWORD_VARIANT_SOURCE_H
#define PE_SWORD_VARIANT_SOURCE_H
typedef struct {float move_speed,sprint_speed,velocity_change_limit;} PeSwordVariantSource;
static const PeSwordVariantSource pe_sword_variant_source = {4.5f,7.0f,12.0f};
#endif
'''
    return {'pe_sword_variant_source.h':header.encode(),'pe_sword_variant_source.json':(json.dumps(metadata,indent=2)+'\n').encode()}


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path,default=ROOT/'rebuild/generated');p.add_argument('--check',action='store_true')
    p.add_argument('--game',type=Path);p.add_argument('--installed-report',type=Path);a=p.parse_args(argv)
    try:
        outputs=build_outputs()
        if bool(a.game)!=bool(a.installed_report):raise ValueError('--game requires a fresh --installed-report and vice versa')
        if a.game:
            if a.installed_report.exists():raise ValueError('Installed report must be fresh')
            definition,_=player.source_definition()
            report=player.verify_installed(a.game,definition)
            a.installed_report.parent.mkdir(parents=True,exist_ok=True)
            with a.installed_report.open('x') as f:json.dump(report,f,indent=2);f.write('\n')
        for name,data in outputs.items():
            path=a.output/name
            if a.check:
                if not path.is_file() or path.read_bytes()!=data:raise ValueError('Stale generated '+name)
            else:a.output.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    except (ValueError,KeyError,OSError,ImportError) as error:print(error,file=sys.stderr);return 1
    print('Sword variant metadata '+('checked' if a.check else 'generated'));return 0


if __name__=='__main__':raise SystemExit(main())
