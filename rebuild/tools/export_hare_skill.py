#!/usr/bin/env python3
"""Export source hare SkInst guide waits; does not observe coroutine timing."""
import argparse
from contextlib import closing
import json
import math
from pathlib import Path
import sqlite3
import struct
import sys
from export_content import ROOT, DEFAULT_DATABASE, connect_readonly, describe_source, numeric_rows
IDS=(30100003,30100004,30100008,30100046,30100047)
SOURCES=('Assets/Scripts/SkillSystem/SkInst.cs','Assets/Scripts/SkillSystem/SkUtils.cs','Assets/Scripts/SkillSystem/SkCond.cs','Assets/Scripts/PETools/PEMath.cs')
DEFAULT_OUTPUT=ROOT/'rebuild/generated'

def number(value):
    n=float(value)
    if not math.isfinite(n) or not 0<=n<=60:raise ValueError('Invalid bounded skill wait')
    return struct.unpack('<f',struct.pack('<f',n))[0]

def expand(value,count):
    values=[number(v) for v in value.split(';')]
    if not 1<=len(values)<=count:raise ValueError('Unexpected skill guide timing count')
    return [values[min(i,len(values)-1)] for i in range(count)]

def build_outputs(database=DEFAULT_DATABASE):
    entries=[]
    with closing(connect_readonly(database)) as db:
        rows,_=numeric_rows(db,'skMain','_id')
        for attack,identity in enumerate(IDS):
            row=rows[identity];guides=2 if attack==2 else 1
            if row['_cond']!=('loopcnt,2' if guides==2 else 'False'):raise ValueError('Unsupported hare skill loop contract')
            if row['_effMainOneTime']!='0' or row['_effMainEachTime']!='0' or row['_effEnding']!='0':raise ValueError('Unported hare guide/ending side effects')
            if row['_effPrepare']!=str(100+attack):raise ValueError('Hare animation effect changed')
            triggers=row['_triggerEvents'].split(';')
            if triggers!=(['10100','10100'] if attack==2 else [str(10400 if attack==3 else 10250 if attack==4 else 10100)]):raise ValueError('Hare external trigger contract changed')
            entry=dict(attack=attack,skill_id=identity,guide_count=guides,
                prepare_pre=number(row['_pretimeOfPrepare']),prepare_post=number(row['_postimeOfPrepare']),
                pre=expand(row['_pretimeOfMain'],guides),main=expand(row['_timeOfMain'],guides),post=expand(row['_postimeOfMain'],guides),
                ending_pre=number(row['_pretimeOfEnding']),ending_post=number(row['_postimeOfEnding']),source_row=dict(row))
            entries.append(entry)
    header=['/* Generated by tools/export_hare_skill.py; do not edit. */','#ifndef PE_HARE_SKILL_SOURCE_H','#define PE_HARE_SKILL_SOURCE_H',
        'static const PeHareSkillDef pe_hare_skill_source[5]={']
    for e in entries:
        arrays=[e[k]+[0.]*(2-len(e[k])) for k in ('pre','main','post')]
        vals=[str(e['skill_id']),str(e['guide_count']),repr(e['prepare_pre']),repr(e['prepare_post'])]
        vals+=['{'+','.join(map(repr,v))+'}' for v in arrays]
        vals+=[repr(e['ending_pre']),repr(e['ending_post'])]
        header.append('    {'+','.join(vals)+'},')
    header+=['};','#endif','']
    manifest=dict(schema=1,database=describe_source(database),sources=[describe_source(ROOT/p) for p in SOURCES],skills=entries,
        scope='Source float-decoded waits only. Native fixed60Hz scheduler is an explicit coroutine cadence adapter; Animator contact windows are independent. No observed timing claim.')
    return {'pe_hare_skill_source.h':'\n'.join(header).encode(),'pe_hare_skill_source.json':(json.dumps(manifest,indent=2)+'\n').encode()}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--database',type=Path,default=DEFAULT_DATABASE);p.add_argument('--output',type=Path,default=DEFAULT_OUTPUT);p.add_argument('--check',action='store_true');a=p.parse_args()
    try:
        output=build_outputs(a.database)
        for name,data in output.items():
            path=a.output/name
            if a.check:
                if not path.is_file() or path.read_bytes()!=data:raise ValueError('Stale '+name)
            else:a.output.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    except (OSError,ValueError,KeyError,sqlite3.Error) as e:print(e,file=sys.stderr);return 1
    print('Hare skill guide export checked' if a.check else 'Hare skill guide export generated');return 0
if __name__=='__main__':raise SystemExit(main())
