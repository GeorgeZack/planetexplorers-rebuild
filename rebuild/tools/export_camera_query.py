#!/usr/bin/env python3
"""Recover layers/shape identities from the qualified settlement bundles.

No Unity/game launch. Requires the existing settlement manifest and UnityPy.
Unknown collider identities fail closed in the camera adapter.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'rebuild/build/reference-assets/adventure-route/route-manifest.json'
LAYER = ROOT / 'Assets/Scripts/ZhouXun/Voxel Creation/Scripts/WhiteCat/PE-VC/Layer.cs'


def recover(manifest=MANIFEST):
    import UnityPy
    layer_text = LAYER.read_text()
    for name, value in {'SceneStatic': 11, 'VFVoxelTerrain': 12, 'Building': 13,
                        'Unwalkable': 16, 'ProxyPlayer': 23}.items():
        if not re.search(r'const\s+int\s+' + name + r'\s*=\s*' + str(value) + r'\s*;', layer_text):
            raise ValueError('Qualified layer changed: ' + name)
    data = json.loads(Path(manifest).read_text())
    groups = []
    sources = []
    cache = {}
    for asset in data['assets']:
        path = Path(asset['source'])
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != asset['sha256']:
            raise ValueError('Qualified settlement bundle changed: ' + path.name)
        if digest not in cache:
            cache[digest] = {o.path_id: o for o in UnityPy.load(str(path)).objects}
        objects = cache[digest]
        sources.append({'entity_id': asset['entity_id'], 'bundle': path.name, 'sha256': digest})
        for part in data['parts']:
            if not part['collision'] or part['entity_id'] != asset['entity_id']:
                continue
            collider = objects[part['component_id']].read_typetree()
            game_object = objects[part['game_object_id']].read_typetree()
            if objects[part['component_id']].type.name != part['kind']:
                raise ValueError('Collider type changed')
            if not collider.get('m_Enabled', True) or collider.get('m_IsTrigger', False):
                raise ValueError('Unsupported disabled/trigger collider')
            if collider['m_GameObject']['m_PathID'] != part['game_object_id']:
                raise ValueError('Collider owner changed')
            layer = game_object['m_Layer']
            if not 0 <= layer < 32 or part['kind'] not in ('BoxCollider', 'MeshCollider'):
                raise ValueError('Unsupported layer/shape')
            groups.append({'entity_id': part['entity_id'], 'component_id': part['component_id'],
                           'game_object_id': part['game_object_id'], 'layer': layer,
                           'convex_solid': part['kind'] == 'BoxCollider' or bool(collider.get('m_Convex', False)),
                           'kind': part['kind']})
    groups.sort(key=lambda g: (g['entity_id'], g['component_id']))
    if len(groups) != 16 or len({(g['entity_id'], g['component_id']) for g in groups}) != len(groups):
        raise ValueError('Qualified sixteen-collider route set changed')
    return {'schema': 1, 'groups': groups, 'sources': sources,
            'layer_source': {'path': str(LAYER.relative_to(ROOT)), 'sha256': hashlib.sha256(LAYER.read_bytes()).hexdigest()},
            'policy': 'Source identities/layers; native inclusive triangle overlap, convex containment and group initial-contact exclusion. No PhysX cooking parity claim.'}


def header(data):
    lines = ['/* Generated by export_camera_query.py; do not edit. */',
             '#ifndef PE_CAMERA_QUERY_SOURCE_H', '#define PE_CAMERA_QUERY_SOURCE_H',
             '#include <stdbool.h>', '#include <stdint.h>',
             'typedef struct { uint32_t entity_id; int64_t component_id; unsigned layer; bool convex_solid; } PeCameraQuerySourceGroup;',
             'static const PeCameraQuerySourceGroup pe_camera_query_source_groups[] = {']
    for g in data['groups']:
        lines.append('    {%du, INT64_C(%d), %du, %s},' % (g['entity_id'], g['component_id'], g['layer'], str(g['convex_solid']).lower()))
    return '\n'.join(lines + ['};', '#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=MANIFEST)
    parser.add_argument('--output', type=Path, default=ROOT / 'rebuild/generated')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = recover(args.manifest)
    outputs = {'pe_camera_query_source.h': header(data),
               'pe_camera_query_source.json': json.dumps(data, indent=2, sort_keys=True) + '\n'}
    for name, value in outputs.items():
        path = args.output / name
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit('Stale camera query metadata: ' + str(path))
        else:
            args.output.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    print('camera query metadata: sixteen qualified static collider identities/layers')


if __name__ == '__main__':
    main()
