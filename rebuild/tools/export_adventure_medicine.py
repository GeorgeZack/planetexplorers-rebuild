#!/usr/bin/env python3
"""Export the checked source transaction contract for Adventure mission9072."""
import argparse
from contextlib import closing
import json
from pathlib import Path
import sqlite3
import sys
from export_content import ROOT, DEFAULT_DATABASE, connect_readonly, describe_source, numeric_rows


def build_outputs(database):
    with closing(connect_readonly(database)) as db:
        quests, _ = numeric_rows(db, 'AdRandomQuest_List', 'ID')
        targets, _ = numeric_rows(db, 'AdQuest_LootItem', 'TargetID')
        items, _ = numeric_rows(db, 'PrototypeItem', 'id')
        chains, _ = numeric_rows(db, 'AdQuestChain', 'QC_ID')
        mission = dict(quests[9072])
        target = dict(targets[2531])
        expected = dict(TargetIDList='2531', Get_MissionItem='877_1', RewardItem='925_10,554_1',
                        CoRemoveItem='917_5', player_talk='4097,4099', TalkOP='0', TalkIN='0',
                        TalkED='4100', NextQuest='0', AutoReply='0', MaxNum='1', bGiveUp='0',
                        IncreaseChain='1', RewardSP='2', Get_DemandItem='0', Get_DeleteItem='0',
                        CoSelRewardItem='0', KeepItem='0')
        for key, value in expected.items():
            if mission[key] != value:
                raise ValueError(f'medicine9072 source contract changed: {key}')
        if any(target[k] != v for k, v in dict(ItemID='917', ItemNum='5', Type='0', ScriptID='0', RandNum='0').items()):
            raise ValueError('medicine target2531 changed')
        if (items[877]['learn'] != '337,388,390' or items[554]['learn'] != '149'
                or quests[9071]['GuanLianList'] != '9072,9073' or quests[9073]['player_talk'] != '4098,0'
                or chains[32]['QusetGroup2'] != '9074,100'):
            raise ValueError('medicine recipe or continuation contract changed')
    header = '''/* Generated by tools/export_adventure_medicine.py; do not edit. */
#ifndef PE_ADVENTURE_MEDICINE_SOURCE_H
#define PE_ADVENTURE_MEDICINE_SOURCE_H
#define PE_MEDICINE_MISSION 9072
#define PE_MEDICINE_TARGET 2531
#define PE_MEDICINE_SCRIPT 877
#define PE_MEDICINE_ITEM 917
#define PE_MEDICINE_REQUIRED 5
static const PeIngredient pe_medicine_rewards[]={{925,10},{554,1}};
#endif
'''
    manifest = dict(schema=1, source=describe_source(database), mission=mission, target=target,
                    acceptance={'talk':4097,'grant':{'item':877,'count':1},'script_formulas':[337,388,390]},
                    decline={'talk':4098,'mission':9073,'repeatable':True,'grant':None},
                    completion={'choice':4099,'final_ack':4100,'consume':{'item':917,'count':5},
                                'rewards':[{'item':925,'count':10},{'item':554,'count':1}]},
                    continuation={'chain':32,'next_group':2,'quest':9074,'implemented':False},
                    skill_reward={'database_value':2,'condition':'Adventure && RandomMapConfig.useSkillTree',
                                  'actual_source_buff':30200126,'actual_source_value':5,'implemented':False},
                    scope='Inventory/progression transactions. UI and physical NPC eligibility remain caller-owned.')
    return {'pe_adventure_medicine_source.h':header.encode(),
            'pe_adventure_medicine_source.json':(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode()}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--database',type=Path,default=DEFAULT_DATABASE)
    parser.add_argument('--output',type=Path,default=ROOT/'rebuild/generated')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    try:
        for name,data in build_outputs(args.database).items():
            path=args.output/name
            if args.check:
                if not path.is_file() or path.read_bytes()!=data:raise ValueError('stale generated '+name)
            else:
                args.output.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        print('Adventure medicine checked' if args.check else 'Adventure medicine generated')
        return 0
    except (OSError,ValueError,KeyError,sqlite3.Error) as error:
        print(error,file=sys.stderr);return 1

if __name__=='__main__':raise SystemExit(main())
