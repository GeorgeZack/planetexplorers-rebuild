#!/usr/bin/env python3
"""Generate native tutorial mound literals from the bounded source C# interpreter."""
import argparse
import hashlib
import re
from pathlib import Path
from export_training_gathering import terrain_samples,TERRAIN,ROOT
DESTINATION=ROOT/'rebuild/generated/pe_training_mound.h'
ANCHORS=ROOT/'Assets/Scripts/Jaluca/TrainingField/EmitlineTask.cs'

def method(source,name):
    tail=source.split('void '+name+'()',1)[1];depth=0
    for i,ch in enumerate(tail):
        if ch=='{':depth+=1
        elif ch=='}':
            depth-=1
            if depth==0:return tail[:i+1]
    raise ValueError('Unclosed source method '+name)

def anchors():
    source=ANCHORS.read_text(encoding='utf-8-sig')
    def read(name):return terrain_samples('void CreatTerrian()'+re.sub(r'\bvol\b','vol0',method(source,name))+'\nIEnumerator FindTerrian()')
    samples=read('CreatTerrian');cleared=read('DestroyTerrian')
    if len(samples)!=32 or any(r[3:]!=[255,1] or not all(-128<=v<=127 for v in r[:3]) for r in samples):raise ValueError('Anchor schema changed')
    if [r[:3] for r in samples]!=[r[:3] for r in cleared] or any(r[3:]!=[0,0] for r in cleared):raise ValueError('Anchor clear samples differ')
    return samples

def generated():
    samples=terrain_samples(TERRAIN.read_text(encoding='utf-8-sig'))
    if len(samples)!=726 or any(not all(-128<=v<=127 for v in row[:3]) or row[4]!=1 for row in samples):
        raise ValueError('Authored mound schema changed')
    source=TERRAIN.read_text(encoding='utf-8-sig')
    tail=source.split('void DestroyTerrian()',1)[1];depth=0;end=None
    for i,ch in enumerate(tail):
        if ch=='{':depth+=1
        elif ch=='}':
            depth-=1
            if depth==0:end=i+1;break
    if end is None:raise ValueError('Unclosed source clear method')
    cleared=terrain_samples('void CreatTerrian()'+tail[:end]+'\nIEnumerator FindTerrian()')
    if [r[:3] for r in cleared]!=[r[:3] for r in samples] or any(r[3:]!=[0,0] for r in cleared):
        raise ValueError('Authored clear samples differ from initialization')
    sha=hashlib.sha256(TERRAIN.read_bytes()).hexdigest()
    lines=['/* Generated by tools/export_training_terrain.py; do not edit.\n',f' * TerrainDigTask.cs SHA256 {sha}. */\n',
           '#ifndef PE_TRAINING_MOUND_H\n#define PE_TRAINING_MOUND_H\n#include <stdint.h>\n',
           'typedef struct { int8_t x,y,z; uint8_t volume; } PeTrainingTerrainSample;\n',
           '#define PE_TRAINING_MOUND_COUNT 726u\n',
           'static const PeTrainingTerrainSample pe_training_mound[PE_TRAINING_MOUND_COUNT]={\n']
    lines += ['    {'+','.join(map(str,row[:4]))+'},\n' for row in samples]
    lines += ['};\n',f'/* EmitlineTask.cs SHA256 {hashlib.sha256(ANCHORS.read_bytes()).hexdigest()} */\n','#define PE_TRAINING_ANCHOR_COUNT 32u\n','static const PeTrainingTerrainSample pe_training_anchors[PE_TRAINING_ANCHOR_COUNT]={\n']
    lines += ['    {'+','.join(map(str,row[:4]))+'},\n' for row in anchors()]
    return ''.join(lines)+'};\n#endif\n'

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path,default=DESTINATION);a=p.parse_args();text=generated()
    if a.check:
        if not a.output.is_file() or a.output.read_text()!=text:p.exit(1,'Training mound generated fixture differs from source\n')
    else:a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(text)
    print('Training mound726 and building anchors32 source samples: '+('verified' if a.check else 'generated'))
if __name__=='__main__':main()
