from export_content import ROOT, DEFAULT_DATABASE, numeric_rows, describe_source, c_float, harvest_item_ids, HARVEST_RESOURCE_IDS
from export_vegetation_source import validate_sources, QUALIFIED, PROTOTYPE_PREFAB
TREE_PREFAB='Assets/Prefabs/tree-Ambient-Occlusion/tree11_grassland.prefab'
TREE_GUID='2055b9405382acf4793ddceef4234dda'
TREE_ID=48
RESOURCE_IDS=HARVEST_RESOURCE_IDS
TREE_CONTRACT={'type':'9','durability':'.48571','production':'279,100;1.2,979,67,1017,100;','fixed_num':'0','self_num':'16','gather_skill':'10006'}

def production(text):
    """NaturalRes stores cumulative cutoffs verbatim, never sum them again."""
    parts=text.split(';')
    def drops(tokens):
        if not tokens or tokens==['']: return []
        if len(tokens)%2: raise ValueError('Incomplete resource production')
        result=[]; previous=0
        for item,threshold in zip(tokens[::2],tokens[1::2]):
            item=int(item); threshold=float(threshold)
            if item<=0 or not math.isfinite(threshold) or not previous<threshold<=100: raise ValueError('Invalid cumulative production')
            result.append(dict(item_id=item,threshold=threshold));previous=threshold
        if len(result)>4: raise ValueError('Too many production alternatives')
        return result
    primary=drops(parts[0].split(',')); extra=[]
    for part in parts[1:] if len(parts)==3 else ('',''):
        tokens=part.split(',');chance=0.; choices=[]
        if len(tokens)>=3 and len(tokens)%2:
            chance=float(tokens[0]);choices=drops(tokens[1:])
            if not math.isfinite(chance) or chance<0: raise ValueError('Invalid optional production chance')
        extra.append(dict(chance=chance,drops=choices))
    return primary,extra

def check_identity(root=ROOT):
    import UnityPy
    from export_sandbox_vegetation_assets import guid
    obj,=[o for o in UnityPy.load(str(root/PROTOTYPE_PREFAB)).objects if o.type.name=='MonoBehaviour']
    refs=obj.read_typetree()['m_treePrototypeList']
    if len(refs)!=512 or guid(obj,refs[TREE_ID])!=TREE_GUID: raise ValueError('Tree prototype identity changed')
    from export_sandbox_world_assets import source_capsule
    _,data=source_capsule()
    if data['prefab']!=TREE_PREFAB or not data['source_mesh_matches_tutorial']:raise ValueError('Rendered tree identity changed')

def build_outputs(root=ROOT,database=DEFAULT_DATABASE):
    sources=validate_sources(root)
    tree=root/TREE_PREFAB; meta=tree.with_suffix('.prefab.meta')
    # Exact binary identity previously decoded by --check-identity. Ordinary
    # checks retain the byte hash, including mesh/collider/material references.
    expected='a94f5931d8fa6cab466004968f0dc73f1eec41fd6c8919874f2f4ae9fc0f442b'
    if hashlib.sha256(tree.read_bytes()).hexdigest()!=expected or 'guid: '+TREE_GUID not in meta.read_text():raise ValueError('Qualified tree prefab changed')
    sources += [tree,meta]
    with sqlite3.connect(database.resolve().as_uri()+'?mode=ro',uri=True) as db:
        db.row_factory=sqlite3.Row;rows,_=numeric_rows(db,'resource','ID'); records=[]
        for id in RESOURCE_IDS:
            row=dict(rows[id]); contract=TREE_CONTRACT if id==1048 else next(q['resource_contract'] for q in QUALIFIED if q['prototype_id']==id-1000)
            if any(row[k]!=v for k,v in contract.items()):raise ValueError('Harvest resource contract changed: '+str(id))
            primary,extra=production(row['production']);records.append(dict(prototype_id=id-1000,row=row,primary=primary,optional=extra[0],rare=extra[1]))
    h=['/* Generated by export_harvest.py; NaturalRes cumulative cutoffs. */','#ifndef PE_HARVEST_SOURCE_H','#define PE_HARVEST_SOURCE_H','#define PE_HARVEST_TREE_PROTOTYPE 48u','static const PeHarvestSource pe_harvest_sources[] = {']
    def group(d): return '{'+','.join('{%d,%s}'%(x['item_id'],c_float(x['threshold'])) for x in d)+('' if d else '{0,0}')+'}'
    for r in records:
        row=r['row'];p=r['primary'];e=r['optional'];s=r['rare']
        h.append('    {%du,%s,%s,%s,%du,%s,{%s,%du,%s},{%s,%du,%s}},'%(r['prototype_id'],c_float(float(row['durability'])),c_float(float(row['fixed_num'])),c_float(float(row['self_num'])),len(p),group(p),c_float(e['chance']),len(e['drops']),group(e['drops']),c_float(s['chance']),len(s['drops']),group(s['drops'])))
    h+=['};','#endif','']
    manifest=dict(format_version=1,sources=[describe_source(database)]+[describe_source(p) for p in sources],tree_identity=dict(prototype_id=48,prefab=TREE_PREFAB,guid=TREE_GUID,mesh='tree11_grassland',unit_instances=True),resources=records,adapters=['Existing saved xorshift32 stream replaces UnityEngine.Random; distribution and draw order reproduced, not Unity seed sequence.','Runtime instances have unit width/height; fixed placement remains unchanged.','No skill-tree rare enablement or quest-specific PlantItemAdd; unsupported source quest hooks remain disabled.','Herb input still commits immediately; source Gather animation and event timing are not ported.','Inventory/RNG/depletion commit atomically; full bag preserves harvest instead of original removal-before-pack behavior.'])
    return {'pe_harvest_source.h':'\n'.join(h).encode(),'pe_harvest_source.json':(json.dumps(manifest,indent=2)+'\n').encode()}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--check-identity',action='store_true');args=p.parse_args()
    if args.check_identity:check_identity()
    for name,data in build_outputs().items():
        path=ROOT/'rebuild/generated'/name
        if args.check:
            if not path.exists() or path.read_bytes()!=data:raise ValueError('Regenerate '+name)
        else:path.write_bytes(data)
    print('Verified' if args.check else 'Generated','harvesting source contract')
if __name__=='__main__':main()
