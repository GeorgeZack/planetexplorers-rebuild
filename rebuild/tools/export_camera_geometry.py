#!/usr/bin/env python3
"""Source/active graph contract for disconnected camera geometry; no Unity needed."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys
from export_camera_environment import ROOT, UPDATE, GUARDS as ENVIRONMENT_GUARDS, graph
from export_content import describe_source

GUARDS = dict(ENVIRONMENT_GUARDS)
GUARDS['Assets/Scripts/Lilj/SystemSettingData.cs'] = 'bbaf09f6410f42a00583469b13ab02f4e4bdcb26fc69750a39992df26a190159'

def validate_sources(root):
    for name,expected in GUARDS.items():
        p=root/name
        if p.is_symlink() or hashlib.sha256(p.read_bytes()).hexdigest()!=expected:
            raise ValueError('Camera geometry source changed: '+name)

def qualify_graph(update):
    p=update['poses']
    links={1:2,2:25,3:24,4:3,17:9,18:17,24:1,25:0,26:13,27:23,29:26}
    for index,previous in links.items():
        if p[index]['poses']['Prev']!=previous:raise ValueError('Camera geometry active path changed')
    if p[3]['kind']!='CameraForge.GeometryClamp' or update['final']['poses']['Final']!=29:
        raise ValueError('Camera geometry node/final changed')
    for index,selection,previous in [(5,0,4),(23,0,5),(9,1,27),(13,0,18)]:
        if p[index]['kind']!='CameraForge.PoseBlend' or p[index]['slots']['Index']['input']!=-1 or p[index]['slots']['Index']['value']['number']!=selection or p[index]['poses'][f'P[{selection}]']!=previous:
            raise ValueError('Camera geometry normal blend changed')
    system=p[2]['modifier'];out=system['output'];nodes=system['nodes']
    if out['kind']!='CameraForge.ConeOutput' or out['slots']['Nearclip']['input']!=-1 or out['slots']['Nearclip']['value']['number']!=struct.unpack('<f',struct.pack('<f',.8))[0]:
        raise ValueError('Active geometry incoming near changed')
    fov=nodes[out['slots']['Fov']['input']]
    if fov['kind']!='CameraForge.GetUserVar' or fov['slots']['Var']['value']['text']!='Original Fov':
        raise ValueError('Active geometry FOV binding changed')
    return dict(normal_path=[0,25,2,1,24,3,4,5,23,27,9,17,18,13,26,29],
        geometry_node=3,incoming_near=out['slots']['Nearclip']['value']['number'],
        fov_input='Original Fov',fov_default=60,system_settings=p[2],geometry=p[3],later_near_modifier=p[26])

def build_outputs(root=ROOT):
    validate_sources(root);qualified=qualify_graph(graph(root/UPDATE))
    constants=dict(MASK='8468481u',DEFAULT_NEAR='.8f',DEFAULT_FOV='60.f',ACTIVITY_FACTOR='.2f',ACTIVITY_MIN='.4f',ACTIVITY_MAX='1.f',
        MIN_RADIUS='.05f',SEARCH_EPSILON='.005f',RING_END='3.01f',RING_STEP='1.5f',CLAMP_SHRINK='.01f',RISE_SHRINK='.02f',
        RISE_FORWARD='.3f',RISE_QUERY_SCALE='10.f',RISE_HIT_FACTOR='.95f',RISE_NEAR_SCALE='2.f',RISE_RADICAND='1.0001f',RISE_LERP='.1f')
    header=['/* Generated by export_camera_geometry.py; do not edit. */','#ifndef PE_CAMERA_GEOMETRY_SOURCE_H','#define PE_CAMERA_GEOMETRY_SOURCE_H']
    header += [f'#define PE_CAMERA_GEOMETRY_{key} {value}' for key,value in constants.items()]
    header += ['#endif','']
    metadata=dict(schema=1,sources=[describe_source(root/p) for p in GUARDS],graph=qualified,
        contract=dict(mask=8468481,ignore_triggers=True,rings=[dict(radius=0,iterations=4),dict(radius=1.5,iterations=4),dict(radius=3,iterations=8)],
            near_search='overlap(min=.05) then overlap(max=near*activity_scale*ur); last clear lower bound while max-min>.005',
            radial_angles='integer360/n in degrees; ray target to ring point before line point to eye; r0 repeats4 times if blocked',
            clamp='If every line blocked OR eye overlap: at most one sphere cast, radius=NCR-.01; hit zeros DistVelocity and sets Geometry Clampd',
            rise='Always sphere cast along normalized worldUp+forward*.3 with radius NCR-.02,range NCR*10; cap hit.distance*.95 or NCR; lerp.1 per evaluation; displace along unnormalized direction',
            distance='Distance from target to corrected position BEFORE rise; DistWanted untouched',
            preview='Read-only evaluator returns proposal; step commits rise only after complete valid success; latch/velocity feedback stays caller-owned'),
        boundaries=['Disconnected mathematical evaluator; no native host or physics backend changed.',
            'Callback provider must explicitly qualify original collider granularity, initial-overlap and crop-boundary semantics.',
            'Primary/auxiliary near-camera projection, reflected picking and pointer origin remain unresolved host work.',
            'Source float math, not bit-identical Unity physics or rendered parity; no desktop/gameplay observation.'])
    validate_sources(root)
    return {'pe_camera_geometry_source.h':'\n'.join(header).encode(),'pe_camera_geometry_source.json':(json.dumps(metadata,indent=2)+'\n').encode()}

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path,default=ROOT/'rebuild/generated');a=p.parse_args(argv)
    try:
        for name,data in build_outputs().items():
            target=a.output/name
            if a.check:
                if not target.is_file() or target.read_bytes()!=data:raise ValueError('Stale camera geometry output '+name)
            else:target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
    except (OSError,ValueError,KeyError,IndexError,struct.error) as e:print(e,file=sys.stderr);return 1
    print('Camera geometry '+('checked' if a.check else 'generated'));return 0
if __name__=='__main__':raise SystemExit(main())
